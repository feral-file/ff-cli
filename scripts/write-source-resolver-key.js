'use strict';

/**
 * Writes src/generated/source-resolver-key.ts, the ff-source-resolver-service
 * client key ff-cli sends as `API-KEY` (src/utilities/source-resolver-client.ts).
 *
 * The key is ff-cli's own named key in the service's CLIENT_API_KEYS. It ships
 * inside the public npm package, which is accepted: it exists for attribution
 * and independent rotation, not secrecy. It is still never committed, so a
 * rotation needs no code change: the release workflow passes the repo Actions
 * secret FF_CLI_SOURCE_RESOLVER_KEY in as FF_SOURCE_RESOLVER_API_KEY and runs
 * this before `npm publish` compiles. The output is gitignored, which keeps
 * the tree clean for scripts/release/cut-release.sh.
 *
 * Usage: node scripts/write-source-resolver-key.js [--require]
 *   --require  fail when FF_SOURCE_RESOLVER_API_KEY is empty, so a release
 *              can never ship without a key by accident.
 * Without --require an absent key writes an empty one: the client then sends
 * no key, which is what local builds and tests do anyway.
 */

const { mkdirSync, writeFileSync } = require('fs');
const { join } = require('path');

const key = (process.env.FF_SOURCE_RESOLVER_API_KEY || '').trim();
if (!key && process.argv.includes('--require')) {
  console.error('FF_SOURCE_RESOLVER_API_KEY is empty; refusing to build a release without it.');
  process.exit(1);
}

const dir = join(__dirname, '..', 'src', 'generated');
mkdirSync(dir, { recursive: true });
writeFileSync(
  join(dir, 'source-resolver-key.ts'),
  [
    '// Generated by scripts/write-source-resolver-key.js. Do not edit or commit.',
    `export const SOURCE_RESOLVER_CLIENT_KEY = ${JSON.stringify(key)};`,
    '',
  ].join('\n')
);
console.log(`Wrote src/generated/source-resolver-key.ts (${key ? 'key set' : 'empty key'}).`);
